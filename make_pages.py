"""Build The Magnetic Wife pages for GoHighLevel.

1. src/build.py renders the full pages into _site/ (letter text, offer, policies).
2. This script turns each page into one self-contained script in docs/
   (sales.js, thank-you.js, privacy.js, terms.js, refunds.js), served by
   GitHub Pages. Each GHL page holds only a two-line loader that pulls its script,
   so changing the page here and pushing updates the live GHL page.

Run:  python3 make_pages.py
"""
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent
SRC = ROOT / "src"
SITE = ROOT / "_site"
DOCS = ROOT / "docs"

subprocess.run([sys.executable, str(SRC / "build.py")], check=True)

css = (SITE / "styles.css").read_text()
css += """
/* Isolation from the GHL page styles */
#tmw-root{display:block;width:100%;margin:0;padding:0;text-align:left}
#tmw-root .letter-page,#tmw-root .simple-page{width:100%}
#tmw-root img{max-width:100%;height:auto}
"""
config_js = (SRC / "config.js").read_text()
site_js = (SITE / "site.js").read_text()

FONTS = "https://fonts.googleapis.com/css2?family=Inter:wght@400;600;700&family=Lora:ital,wght@0,400;0,700;1,400&family=Playfair+Display:ital,wght@0,400;0,700;1,400&display=swap"
PIXEL = """
if (!window.fbq && C.pixelId) {
  !function(f,b,e,v,n,t,s){if(f.fbq)return;n=f.fbq=function(){n.callMethod?n.callMethod.apply(n,arguments):n.queue.push(arguments)};if(!f._fbq)f._fbq=n;n.push=n;n.loaded=!0;n.version='2.0';n.queue=[];t=b.createElement(e);t.async=!0;t.src=v;s=b.getElementsByTagName(e)[0];s.parentNode.insertBefore(t,s)}(window,document,'script','https://connect.facebook.net/en_US/fbevents.js');
  fbq('init', C.pixelId);
  fbq('track', 'PageView');
}
"""


def body_of(path):
    html = path.read_text()
    body = re.search(r"<body>(.*)</body>", html, re.S).group(1)
    body = re.sub(r"<script\b.*?</script>", "", body, flags=re.S)
    body = re.sub(r"<noscript>.*?</noscript>", "", body, flags=re.S)
    for a, b in [("/privacy/", "/privacy"), ("/terms/", "/terms"), ("/refunds/", "/refunds")]:
        body = body.replace(f'href="{a}"', f'href="{b}"')
    return body.strip()


def purchase_js():
    html = (SITE / "thank-you" / "index.html").read_text()
    return re.search(r"<script>\s*(\(function\(\)\{.*?\}\)\(\);)\s*</script>", html, re.S).group(1)


def bundle(name, body, after=""):
    body = body.replace('src="/bundle.webp"', 'src="__BASE__bundle.jpg"').replace(' loading="lazy"', "")
    return f"""/* The Magnetic Wife: {name} page. Generated by make_pages.py, edit src/ instead. */
(function () {{
  var me = document.currentScript;
  var BASE = me && me.src ? me.src.replace(/[^/]*(\\?.*)?$/, "") : "";
{config_js}
  var C = window.TMW;
{PIXEL}
  if (!document.querySelector('link[data-tmw-fonts]')) {{
    var f = document.createElement("link");
    f.rel = "stylesheet"; f.href = {json.dumps(FONTS)}; f.setAttribute("data-tmw-fonts", "1");
    document.head.appendChild(f);
  }}
  var st = document.createElement("style");
  st.textContent = {json.dumps(css)};
  document.head.appendChild(st);
  var root = document.getElementById("tmw-root");
  if (!root) {{ root = document.createElement("div"); root.id = "tmw-root"; me.parentNode.insertBefore(root, me); }}
  root.innerHTML = {json.dumps(body)}.split("__BASE__").join(BASE);
{after}
}})();
"""


pages = {
    "sales": (body_of(SITE / "index.html"), site_js),
    "thank-you": (body_of(SITE / "thank-you" / "index.html"), purchase_js()),
    "privacy": (body_of(SITE / "privacy" / "index.html"), ""),
    "terms": (body_of(SITE / "terms" / "index.html"), ""),
    "refunds": (body_of(SITE / "refunds" / "index.html"), ""),
}
DOCS.mkdir(exist_ok=True)
for name, (body, after) in pages.items():
    (DOCS / f"{name}.js").write_text(bundle(name, body, after))

(DOCS / ".nojekyll").write_text("")
(DOCS / "index.html").write_text("""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex"><title>The Magnetic Wife: page preview</title></head>
<body style="margin:0"><div id="tmw-root"></div><script src="sales.js"></script></body></html>
""")
print("docs/ ready:", ", ".join(f"{n}.js" for n in pages))
